-- Campus Pantry revised schema. PostgreSQL 15+.
-- Run in a fresh database. Review and test before production use.
BEGIN;
CREATE SCHEMA IF NOT EXISTS campus_pantry;
SET search_path = campus_pantry, public;

CREATE SEQUENCE IF NOT EXISTS stock_number_seq START 1;

CREATE TABLE person (
    unikey varchar(30) PRIMARY KEY CHECK (unikey ~ '^[a-z]{4}[0-9]{4}$'),
    full_name varchar(120) NOT NULL,
    email varchar(254) NOT NULL,
    contact varchar(40)
);

CREATE TABLE student (
    unikey varchar(30) PRIMARY KEY REFERENCES person(unikey),
    degree_level varchar(20) CHECK (degree_level IN ('BACHELOR','POSTGRADUATE')),
    student_category varchar(20) CHECK (student_category IN ('DOMESTIC','INTERNATIONAL'))
);

CREATE TABLE volunteer (
    unikey varchar(30) PRIMARY KEY REFERENCES person(unikey),
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE staff (
    unikey varchar(30) PRIMARY KEY REFERENCES person(unikey),
    staff_code varchar(30) NOT NULL UNIQUE,
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE pantry_shift (
    shift_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_date date NOT NULL,
    start_time time NOT NULL,
    end_time time NOT NULL,
    status varchar(10) NOT NULL DEFAULT 'PLANNED'
        CHECK (status IN ('PLANNED','OPEN','CLOSED')),
    CHECK (end_time > start_time),
    UNIQUE (shift_date, start_time)
);

CREATE TABLE session (
    session_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_id integer NOT NULL REFERENCES pantry_shift(shift_id),
    session_date date NOT NULL,
    start_time time NOT NULL,
    end_time time NOT NULL,
    capacity integer NOT NULL DEFAULT 50 CHECK (capacity BETWEEN 1 AND 50),
    CHECK (end_time > start_time),
    UNIQUE (session_date, start_time)
);

CREATE TABLE shift_staff_assignment (
    shift_id integer NOT NULL REFERENCES pantry_shift(shift_id),
    staff_unikey varchar(30) NOT NULL REFERENCES staff(unikey),
    assignment_role varchar(20) NOT NULL
        CHECK (assignment_role IN ('MAIN_SUPERVISOR','ASSISTANT')),
    PRIMARY KEY (shift_id, staff_unikey),
    UNIQUE (shift_id, assignment_role)
);

CREATE TABLE volunteer_shift (
    shift_id integer NOT NULL REFERENCES pantry_shift(shift_id),
    volunteer_unikey varchar(30) NOT NULL REFERENCES volunteer(unikey),
    status varchar(12) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    request_date timestamptz NOT NULL DEFAULT now(),
    reviewed_by_staff varchar(30) REFERENCES staff(unikey),
    reviewed_at timestamptz,
    PRIMARY KEY (shift_id, volunteer_unikey)
);

CREATE TABLE booking (
    booking_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_unikey varchar(30) NOT NULL REFERENCES student(unikey),
    session_id integer NOT NULL REFERENCES session(session_id),
    status varchar(12) NOT NULL DEFAULT 'CONFIRMED'
        CHECK (status IN ('CONFIRMED','ATTENDED','ABSENT','CANCELLED')),
    qr_token varchar(100) NOT NULL UNIQUE,
    created_at timestamptz NOT NULL DEFAULT now(),
    attendance_at timestamptz,
    admin_override boolean NOT NULL DEFAULT false,
    override_by_staff varchar(30) REFERENCES staff(unikey),
    override_reason varchar(250),
    CHECK ((admin_override = false AND override_by_staff IS NULL)
        OR (admin_override = true AND override_by_staff IS NOT NULL)),
    CHECK ((status = 'ATTENDED' AND attendance_at IS NOT NULL)
        OR (status <> 'ATTENDED'))
);

CREATE TABLE purchase_record (
    purchase_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recorded_by_staff varchar(30) NOT NULL REFERENCES staff(unikey),
    purchase_date date NOT NULL,
    reference varchar(80),
    notes varchar(250)
);

CREATE TABLE product (
    product_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_code varchar(30) NOT NULL UNIQUE,
    product_name varchar(120) NOT NULL,
    category varchar(60) NOT NULL,
    counting_unit varchar(30) NOT NULL,
    low_stock_threshold integer NOT NULL DEFAULT 0 CHECK (low_stock_threshold >= 0)
);

CREATE TABLE purchase_record_line (
    purchase_line_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id bigint NOT NULL REFERENCES purchase_record(purchase_id),
    product_id integer NOT NULL REFERENCES product(product_id),
    quantity integer NOT NULL CHECK (quantity > 0),
    unit_cost numeric(10,2) CHECK (unit_cost IS NULL OR unit_cost >= 0)
);

CREATE TABLE stock_batch (
    stock_number varchar(20) PRIMARY KEY
        DEFAULT ('STK-' || lpad(nextval('stock_number_seq')::text, 6, '0')),
    product_id integer NOT NULL REFERENCES product(product_id),
    purchase_line_id bigint NOT NULL REFERENCES purchase_record_line(purchase_line_id),
    batch_code varchar(60),
    received_on date NOT NULL,
    expires_on date,
    received_qty integer NOT NULL CHECK (received_qty >= 0),
    CHECK (expires_on IS NULL OR expires_on >= received_on)
);

CREATE TABLE stock_count (
    stock_count_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_number varchar(20) NOT NULL REFERENCES stock_batch(stock_number),
    shift_id integer REFERENCES pantry_shift(shift_id),
    counted_by_staff varchar(30) NOT NULL REFERENCES staff(unikey),
    counted_at timestamptz NOT NULL DEFAULT now(),
    count_type varchar(12) NOT NULL CHECK (count_type IN ('OPENING','CLOSING','SPOT_CHECK')),
    counted_qty integer NOT NULL CHECK (counted_qty >= 0),
    notes varchar(250)
);

-- Shift-level opening/closing count pair retained from the original project design.
CREATE TABLE shift_stock_count (
    shift_id integer NOT NULL REFERENCES pantry_shift(shift_id),
    stock_number varchar(20) NOT NULL REFERENCES stock_batch(stock_number),
    opening_qty integer NOT NULL CHECK (opening_qty >= 0),
    closing_qty integer CHECK (closing_qty >= 0),
    opening_variance_reason varchar(250),
    PRIMARY KEY (shift_id, stock_number)
);

CREATE TABLE stock_adjustment (
    shift_id integer NOT NULL,
    stock_number varchar(20) NOT NULL,
    adjustment_kind varchar(10) NOT NULL CHECK (adjustment_kind IN ('RECEIPT','WASTE')),
    quantity integer NOT NULL CHECK (quantity > 0),
    reason varchar(250) NOT NULL CHECK (length(btrim(reason)) > 0),
    PRIMARY KEY (shift_id, stock_number, adjustment_kind),
    FOREIGN KEY (shift_id, stock_number)
        REFERENCES shift_stock_count(shift_id, stock_number)
);

CREATE INDEX booking_by_session ON booking(session_id, status);
CREATE INDEX booking_by_student ON booking(student_unikey);
CREATE INDEX stock_batch_by_product ON stock_batch(product_id);
CREATE INDEX stock_batch_by_expiry ON stock_batch(expires_on);
CREATE INDEX stock_count_by_batch_time ON stock_count(stock_number, counted_at DESC);
CREATE INDEX shift_count_by_batch ON shift_stock_count(stock_number);

-- Cross-row booking rule: one active booking per student per date by default,
-- and no more than the session capacity. Admin overrides are explicit.
-- Row locks on session AND student guarantee concurrency safety.
CREATE OR REPLACE FUNCTION validate_booking() RETURNS trigger
LANGUAGE plpgsql SET search_path = campus_pantry, public AS $$
DECLARE
    target_date date;
    target_capacity integer;
    active_count integer;
    duplicate_count integer;
BEGIN
    -- Moving between active states (e.g. CONFIRMED -> ATTENDED / ABSENT)
    -- or cancelling does not add booking load; skip re-validation.
    IF TG_OP = 'UPDATE'
       AND NEW.session_id = OLD.session_id
       AND NEW.student_unikey = OLD.student_unikey
       AND (OLD.status <> 'CANCELLED' OR NEW.status = 'CANCELLED') THEN
        RETURN NEW;
    END IF;

    -- Concurrency locks: lock session row and student row
    SELECT session_date, capacity INTO target_date, target_capacity
    FROM session WHERE session_id = NEW.session_id FOR UPDATE;

    PERFORM 1 FROM student WHERE unikey = NEW.student_unikey FOR UPDATE;

    IF NEW.status <> 'CANCELLED' THEN
        SELECT count(*) INTO active_count
        FROM booking b
        WHERE b.session_id = NEW.session_id
          AND b.status <> 'CANCELLED'
          AND b.booking_id IS DISTINCT FROM NEW.booking_id;

        IF active_count >= target_capacity THEN
            RAISE EXCEPTION 'Session capacity of % has been reached', target_capacity;
        END IF;

        IF NOT NEW.admin_override THEN
            SELECT count(*) INTO duplicate_count
            FROM booking b JOIN session s ON s.session_id = b.session_id
            WHERE b.student_unikey = NEW.student_unikey
              AND s.session_date = target_date
              AND b.status <> 'CANCELLED'
              AND b.booking_id IS DISTINCT FROM NEW.booking_id;
            IF duplicate_count > 0 THEN
                RAISE EXCEPTION 'Student already has an active booking on this date';
            END IF;
        END IF;
    END IF;

    IF NEW.admin_override THEN
        IF NEW.override_by_staff IS NULL THEN
            RAISE EXCEPTION 'Admin override must identify the staff member';
        END IF;
        IF NEW.override_reason IS NULL OR length(btrim(NEW.override_reason)) = 0 THEN
            RAISE EXCEPTION 'Admin override must include a valid reason';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER booking_validate_before_write
BEFORE INSERT OR UPDATE OF student_unikey, session_id, status, admin_override, override_by_staff, override_reason
ON booking FOR EACH ROW EXECUTE FUNCTION validate_booking();

-- Staff Shift Overlap Trigger: prevent assigning a staff member to overlapping shifts
CREATE OR REPLACE FUNCTION validate_staff_shift_overlap() RETURNS trigger
LANGUAGE plpgsql SET search_path = campus_pantry, public AS $$
DECLARE
    cur_date date;
    cur_start time;
    cur_end time;
    overlap_count integer;
BEGIN
    SELECT shift_date, start_time, end_time INTO cur_date, cur_start, cur_end
    FROM pantry_shift WHERE shift_id = NEW.shift_id;

    SELECT count(*) INTO overlap_count
    FROM shift_staff_assignment ssa
    JOIN pantry_shift ps ON ps.shift_id = ssa.shift_id
    WHERE ssa.staff_unikey = NEW.staff_unikey
      AND ssa.shift_id <> NEW.shift_id
      AND ps.shift_date = cur_date
      AND ps.start_time < cur_end
      AND cur_start < ps.end_time;

    IF overlap_count > 0 THEN
        RAISE EXCEPTION 'Staff member % is already assigned to an overlapping shift on %', NEW.staff_unikey, cur_date;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER staff_shift_overlap_validate
BEFORE INSERT OR UPDATE OF shift_id, staff_unikey
ON shift_staff_assignment FOR EACH ROW EXECUTE FUNCTION validate_staff_shift_overlap();

-- Volunteer Shift Overlap Trigger: prevent volunteer from having overlapping approved/pending shifts
CREATE OR REPLACE FUNCTION validate_volunteer_shift_overlap() RETURNS trigger
LANGUAGE plpgsql SET search_path = campus_pantry, public AS $$
DECLARE
    cur_date date;
    cur_start time;
    cur_end time;
    overlap_count integer;
BEGIN
    IF NEW.status IN ('PENDING', 'APPROVED') THEN
        SELECT shift_date, start_time, end_time INTO cur_date, cur_start, cur_end
        FROM pantry_shift WHERE shift_id = NEW.shift_id;

        SELECT count(*) INTO overlap_count
        FROM volunteer_shift vs
        JOIN pantry_shift ps ON ps.shift_id = vs.shift_id
        WHERE vs.volunteer_unikey = NEW.volunteer_unikey
          AND vs.shift_id <> NEW.shift_id
          AND vs.status IN ('PENDING', 'APPROVED')
          AND ps.shift_date = cur_date
          AND ps.start_time < cur_end
          AND cur_start < ps.end_time;

        IF overlap_count > 0 THEN
            RAISE EXCEPTION 'Volunteer % has an overlapping shift request or assignment on %', NEW.volunteer_unikey, cur_date;
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER volunteer_shift_overlap_validate
BEFORE INSERT OR UPDATE OF shift_id, volunteer_unikey, status
ON volunteer_shift FOR EACH ROW EXECUTE FUNCTION validate_volunteer_shift_overlap();

-- Prevent overlapping shift sessions and ensure a session falls within a shift.
CREATE OR REPLACE FUNCTION validate_session_shift() RETURNS trigger
LANGUAGE plpgsql SET search_path = campus_pantry, public AS $$
DECLARE
     sd date; ss time; se time; sh_start time; sh_end time; sh_date date;
BEGIN
     SELECT shift_date, start_time, end_time INTO sh_date, sh_start, sh_end
     FROM pantry_shift WHERE shift_id = NEW.shift_id;
     IF NEW.session_date <> sh_date OR NEW.start_time < sh_start OR NEW.end_time > sh_end THEN
         RAISE EXCEPTION 'Session must fall within the assigned shift date and time';
     END IF;
     RETURN NEW;
END;
$$;

CREATE TRIGGER session_shift_validate
BEFORE INSERT OR UPDATE OF shift_id, session_date, start_time, end_time
ON session FOR EACH ROW EXECUTE FUNCTION validate_session_shift();

-- Shift staffing completeness trigger: exactly 1 supervisor & 1 assistant required for OPEN/CLOSED shifts
CREATE OR REPLACE FUNCTION validate_shift_status() RETURNS trigger
LANGUAGE plpgsql SET search_path = campus_pantry, public AS $$
DECLARE
    super_cnt integer;
    asst_cnt integer;
BEGIN
    IF NEW.status IN ('OPEN', 'CLOSED') THEN
        SELECT count(*) FILTER (WHERE assignment_role = 'MAIN_SUPERVISOR'),
               count(*) FILTER (WHERE assignment_role = 'ASSISTANT')
        INTO super_cnt, asst_cnt
        FROM shift_staff_assignment
        WHERE shift_id = NEW.shift_id;

        IF super_cnt <> 1 OR asst_cnt <> 1 THEN
            RAISE EXCEPTION 'Shift % must have exactly 1 MAIN_SUPERVISOR and 1 ASSISTANT before it can be %', NEW.shift_id, NEW.status;
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER shift_status_validate
BEFORE INSERT OR UPDATE OF status
ON pantry_shift FOR EACH ROW EXECUTE FUNCTION validate_shift_status();

-- Ensure stock batch product matches purchase record line product
CREATE OR REPLACE FUNCTION validate_stock_batch_product() RETURNS trigger
LANGUAGE plpgsql SET search_path = campus_pantry, public AS $$
DECLARE
    prl_prod integer;
BEGIN
    SELECT product_id INTO prl_prod FROM purchase_record_line WHERE purchase_line_id = NEW.purchase_line_id;
    IF prl_prod IS DISTINCT FROM NEW.product_id THEN
        RAISE EXCEPTION 'Stock batch product_id (%) does not match purchase line product_id (%)', NEW.product_id, prl_prod;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER stock_batch_product_validate
BEFORE INSERT OR UPDATE OF product_id, purchase_line_id
ON stock_batch FOR EACH ROW EXECUTE FUNCTION validate_stock_batch_product();

-- Views
CREATE OR REPLACE VIEW v_booking_attendance AS
SELECT s.session_date, s.session_id, s.start_time, s.end_time, s.capacity,
       count(b.booking_id) FILTER (WHERE b.status <> 'CANCELLED') AS active_bookings,
       count(b.booking_id) FILTER (WHERE b.status = 'ATTENDED') AS attended,
       count(b.booking_id) FILTER (WHERE b.status = 'ABSENT') AS absent,
       count(b.booking_id) FILTER (WHERE b.status = 'CONFIRMED') AS awaiting_checkin,
       s.capacity - count(b.booking_id) FILTER (WHERE b.status <> 'CANCELLED') AS spaces_remaining
FROM session s LEFT JOIN booking b ON b.session_id = s.session_id
GROUP BY s.session_id;

CREATE OR REPLACE VIEW v_latest_stock_count AS
SELECT DISTINCT ON (sc.stock_number)
       sc.stock_number, sb.product_id, p.product_name, p.counting_unit,
       sc.counted_qty AS last_counted_qty, sc.counted_at, sc.count_type,
       sc.counted_by_staff
FROM stock_count sc
JOIN stock_batch sb ON sb.stock_number = sc.stock_number
JOIN product p ON p.product_id = sb.product_id
ORDER BY sc.stock_number, sc.counted_at DESC, sc.stock_count_id DESC;

CREATE OR REPLACE VIEW v_shift_stock_report AS
SELECT sh.shift_id, sh.shift_date, sh.start_time, sh.end_time,
       ssc.stock_number, p.product_id, p.product_name, p.counting_unit,

       ssc.opening_qty, coalesce(r.quantity,0) AS received_qty,
       coalesce(w.quantity,0) AS waste_qty, ssc.closing_qty,
       CASE WHEN sh.status = 'CLOSED' AND ssc.closing_qty IS NOT NULL
            THEN ssc.opening_qty + coalesce(r.quantity,0)
                 - coalesce(w.quantity,0) - ssc.closing_qty END AS estimated_dispensed_qty,
       ssc.opening_variance_reason
FROM shift_stock_count ssc
JOIN pantry_shift sh ON sh.shift_id = ssc.shift_id
JOIN stock_batch sb ON sb.stock_number = ssc.stock_number
JOIN product p ON p.product_id = sb.product_id
LEFT JOIN stock_adjustment r ON r.shift_id = ssc.shift_id
    AND r.stock_number = ssc.stock_number AND r.adjustment_kind = 'RECEIPT'
LEFT JOIN stock_adjustment w ON w.shift_id = ssc.shift_id
    AND w.stock_number = ssc.stock_number AND w.adjustment_kind = 'WASTE';

COMMIT;
