-- Campus Pantry final university showcase schema. PostgreSQL 15+.
-- Run only in an empty database. Existing schemas are never replaced here.
BEGIN;
CREATE SCHEMA campus_pantry;
SET search_path = campus_pantry, public;

CREATE SEQUENCE stock_number_seq START 1;

CREATE TABLE person (
    unikey varchar(30) PRIMARY KEY CHECK (unikey ~ '^[a-z]{4}[0-9]{4}$'),
    full_name varchar(120) NOT NULL,
    email varchar(254) NOT NULL,
    contact varchar(40)
);

CREATE TABLE student (
    unikey varchar(30) PRIMARY KEY REFERENCES person(unikey),
    degree_level varchar(20) CHECK (degree_level IN ('BACHELOR','POSTGRADUATE')),
    student_category varchar(20) CHECK (student_category IN ('DOMESTIC','INTERNATIONAL'))
);

CREATE TABLE volunteer (
    unikey varchar(30) PRIMARY KEY REFERENCES person(unikey),
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE staff (
    unikey varchar(30) PRIMARY KEY REFERENCES person(unikey),
    staff_code varchar(30) NOT NULL UNIQUE,
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE pantry_shift (
    shift_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_date date NOT NULL,
    start_time time NOT NULL,
    end_time time NOT NULL,
    status varchar(10) NOT NULL DEFAULT 'PLANNED'
        CHECK (status IN ('PLANNED','OPEN','CLOSED')),
    CHECK (end_time > start_time),
    UNIQUE (shift_date, start_time)
);

CREATE TABLE session (
    session_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_id integer NOT NULL REFERENCES pantry_shift(shift_id),
    session_date date NOT NULL,
    start_time time NOT NULL,
    end_time time NOT NULL,
    capacity integer NOT NULL DEFAULT 50 CHECK (capacity BETWEEN 1 AND 50),
    CHECK (end_time > start_time),
    UNIQUE (session_date, start_time)
);

CREATE TABLE shift_staff_assignment (
    shift_id integer NOT NULL REFERENCES pantry_shift(shift_id),
    staff_unikey varchar(30) NOT NULL REFERENCES staff(unikey),
    assignment_role varchar(20) NOT NULL
        CHECK (assignment_role IN ('MAIN_SUPERVISOR','ASSISTANT')),
    PRIMARY KEY (shift_id, staff_unikey),
    UNIQUE (shift_id, assignment_role)
);

CREATE TABLE volunteer_shift (
    shift_id integer NOT NULL REFERENCES pantry_shift(shift_id),
    volunteer_unikey varchar(30) NOT NULL REFERENCES volunteer(unikey),
    status varchar(12) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    request_date timestamptz NOT NULL DEFAULT now(),
    reviewed_by_staff varchar(30) REFERENCES staff(unikey),
    reviewed_at timestamptz,
    PRIMARY KEY (shift_id, volunteer_unikey)
);

CREATE TABLE booking (
    booking_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_unikey varchar(30) NOT NULL REFERENCES student(unikey),
    session_id integer NOT NULL REFERENCES session(session_id),
    status varchar(12) NOT NULL DEFAULT 'CONFIRMED'
        CHECK (status IN ('CONFIRMED','ATTENDED','ABSENT','CANCELLED')),
    qr_token varchar(100) NOT NULL UNIQUE,
    created_at timestamptz NOT NULL DEFAULT now(),
    attendance_at timestamptz,
    admin_override boolean NOT NULL DEFAULT false,
    override_by_staff varchar(30) REFERENCES staff(unikey),
    override_reason varchar(250),
    CONSTRAINT booking_override_consistency CHECK (
        (NOT admin_override AND override_by_staff IS NULL AND override_reason IS NULL)
        OR (admin_override AND override_by_staff IS NOT NULL
            AND override_reason IS NOT NULL AND length(btrim(override_reason)) > 0)),
    CONSTRAINT booking_attendance_consistency CHECK (
        (status = 'ATTENDED') = (attendance_at IS NOT NULL))
);

CREATE TABLE purchase_record (
    purchase_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recorded_by_staff varchar(30) NOT NULL REFERENCES staff(unikey),
    purchase_date date NOT NULL,
    reference varchar(80),
    notes varchar(250)
);

CREATE TABLE product (
    product_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_code varchar(30) NOT NULL UNIQUE,
    product_name varchar(120) NOT NULL,
    category varchar(60) NOT NULL,
    counting_unit varchar(30) NOT NULL,
    low_stock_threshold integer NOT NULL DEFAULT 0 CHECK (low_stock_threshold >= 0)
);

CREATE TABLE purchase_record_line (
    purchase_line_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id bigint NOT NULL REFERENCES purchase_record(purchase_id),
    product_id integer NOT NULL REFERENCES product(product_id),
    quantity integer NOT NULL CHECK (quantity > 0),
    unit_cost numeric(10,2) CHECK (unit_cost IS NULL OR unit_cost >= 0),
    UNIQUE (purchase_line_id, product_id)
);

CREATE TABLE stock_batch (
    stock_number varchar(20) PRIMARY KEY
        DEFAULT ('STK-' || lpad(nextval('stock_number_seq')::text, 6, '0'))
        CHECK (stock_number ~ '^STK-[0-9]{6}$'),
    product_id integer NOT NULL REFERENCES product(product_id),
    purchase_line_id bigint NOT NULL,
    batch_code varchar(60),
    received_on date NOT NULL,
    expires_on date,
    received_qty integer NOT NULL CHECK (received_qty >= 0),
    CHECK (expires_on IS NULL OR expires_on >= received_on),
    CONSTRAINT stock_batch_purchase_product_fkey FOREIGN KEY (purchase_line_id, product_id)
        REFERENCES purchase_record_line(purchase_line_id, product_id)
);

CREATE TABLE stock_count (
    stock_count_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_number varchar(20) NOT NULL REFERENCES stock_batch(stock_number),
    shift_id integer REFERENCES pantry_shift(shift_id),
    counted_by_staff varchar(30) NOT NULL REFERENCES staff(unikey),
    counted_at timestamptz NOT NULL DEFAULT now(),
    count_type varchar(12) NOT NULL CHECK (count_type IN ('OPENING','CLOSING','SPOT_CHECK')),
    counted_qty integer NOT NULL CHECK (counted_qty >= 0),
    notes varchar(250)
);

-- Shift-level opening/closing count pair retained from the original project design.
CREATE TABLE shift_stock_count (
    shift_id integer NOT NULL REFERENCES pantry_shift(shift_id),
    stock_number varchar(20) NOT NULL REFERENCES stock_batch(stock_number),
    opening_qty integer NOT NULL CHECK (opening_qty >= 0),
    closing_qty integer CHECK (closing_qty >= 0),
    opening_variance_reason varchar(250),
    PRIMARY KEY (shift_id, stock_number)
);

CREATE TABLE stock_adjustment (
    shift_id integer NOT NULL,
    stock_number varchar(20) NOT NULL,
    adjustment_kind varchar(10) NOT NULL CHECK (adjustment_kind IN ('RECEIPT','WASTE')),
    quantity integer NOT NULL CHECK (quantity > 0),
    reason varchar(250) NOT NULL CHECK (length(btrim(reason)) > 0),
    PRIMARY KEY (shift_id, stock_number, adjustment_kind),
    FOREIGN KEY (shift_id, stock_number)
        REFERENCES shift_stock_count(shift_id, stock_number)
);

CREATE INDEX booking_by_session ON booking(session_id, status);
CREATE INDEX booking_by_student ON booking(student_unikey);
CREATE INDEX stock_batch_by_product ON stock_batch(product_id);
CREATE INDEX stock_batch_by_expiry ON stock_batch(expires_on);
CREATE INDEX stock_count_by_batch_time ON stock_count(stock_number, counted_at DESC, stock_count_id DESC);
CREATE INDEX shift_count_by_batch ON shift_stock_count(stock_number);
CREATE INDEX assignments_by_staff ON shift_staff_assignment(staff_unikey, shift_id);
CREATE INDEX requests_by_volunteer ON volunteer_shift(volunteer_unikey, shift_id);

-- All booking writers acquire student locks before session locks.
CREATE FUNCTION validate_booking() RETURNS trigger
LANGUAGE plpgsql SET search_path = campus_pantry, public AS $$
DECLARE
    target_date date;
    target_capacity integer;
    active_count integer;
    duplicate_count integer;
    students_to_lock varchar[];
    sessions_to_lock integer[];
    check_load boolean := true;
BEGIN
    -- Audit metadata is checked on every write, including status-only updates.
    IF NEW.admin_override THEN
        IF NEW.override_by_staff IS NULL THEN
            RAISE EXCEPTION 'Admin override must identify the staff member';
        END IF;
        IF NEW.override_reason IS NULL OR length(btrim(NEW.override_reason)) = 0 THEN
            RAISE EXCEPTION 'Admin override must include a valid reason';
        END IF;
        IF TG_OP = 'INSERT' OR NEW.override_by_staff IS DISTINCT FROM OLD.override_by_staff
           OR NEW.admin_override IS DISTINCT FROM OLD.admin_override THEN
            IF NOT EXISTS (SELECT 1 FROM staff WHERE unikey=NEW.override_by_staff AND is_active) THEN
                RAISE EXCEPTION 'Admin override requires an active staff member';
            END IF;
        END IF;
    ELSIF NEW.override_by_staff IS NOT NULL OR NEW.override_reason IS NOT NULL THEN
        RAISE EXCEPTION 'A non-override booking cannot retain override metadata';
    END IF;

    IF TG_OP = 'UPDATE' THEN
        check_load := NEW.student_unikey IS DISTINCT FROM OLD.student_unikey
            OR NEW.session_id IS DISTINCT FROM OLD.session_id
            OR (OLD.status = 'CANCELLED' AND NEW.status <> 'CANCELLED')
            OR (OLD.admin_override AND NOT NEW.admin_override);
    END IF;
    IF NOT check_load OR NEW.status = 'CANCELLED' THEN
        RETURN NEW;
    END IF;

    students_to_lock := ARRAY[NEW.student_unikey];
    sessions_to_lock := ARRAY[NEW.session_id];
    IF TG_OP = 'UPDATE' THEN
        students_to_lock := array_append(students_to_lock, OLD.student_unikey);
        sessions_to_lock := array_append(sessions_to_lock, OLD.session_id);
    END IF;
    PERFORM unikey FROM student WHERE unikey = ANY(students_to_lock)
        ORDER BY unikey FOR UPDATE;
    PERFORM session_id FROM session WHERE session_id = ANY(sessions_to_lock)
        ORDER BY session_id FOR UPDATE;
    SELECT session_date, capacity INTO target_date, target_capacity
        FROM session WHERE session_id = NEW.session_id;

    SELECT count(*) INTO active_count FROM booking
    WHERE session_id=NEW.session_id AND status <> 'CANCELLED'
      AND booking_id IS DISTINCT FROM NEW.booking_id;
    IF active_count >= target_capacity THEN
        RAISE EXCEPTION 'Session capacity of % has been reached', target_capacity;
    END IF;
    IF NOT NEW.admin_override THEN
        SELECT count(*) INTO duplicate_count
        FROM booking b JOIN session s ON s.session_id=b.session_id
        WHERE b.student_unikey=NEW.student_unikey AND s.session_date=target_date
          AND b.status <> 'CANCELLED' AND b.booking_id IS DISTINCT FROM NEW.booking_id;
        IF duplicate_count > 0 THEN
            RAISE EXCEPTION 'Student already has an active booking on this date';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER booking_validate_before_write
BEFORE INSERT OR UPDATE ON booking
FOR EACH ROW EXECUTE FUNCTION validate_booking();

-- Staff assignment changes lock the staff record, then affected shift records.
-- An opened shift's staffing is frozen, preserving historical completeness.
CREATE FUNCTION validate_staff_shift_assignment() RETURNS trigger
LANGUAGE plpgsql SET search_path = campus_pantry, public AS $$
DECLARE
    people varchar[];
    shifts integer[];
    sh record;
BEGIN
    IF TG_OP='DELETE' THEN
        people:=ARRAY[OLD.staff_unikey]; shifts:=ARRAY[OLD.shift_id];
    ELSE
        people:=ARRAY[NEW.staff_unikey]; shifts:=ARRAY[NEW.shift_id];
        IF TG_OP='UPDATE' THEN
            people:=array_append(people,OLD.staff_unikey);
            shifts:=array_append(shifts,OLD.shift_id);
        END IF;
    END IF;
    PERFORM unikey FROM staff WHERE unikey=ANY(people) ORDER BY unikey FOR UPDATE;
    PERFORM shift_id FROM pantry_shift WHERE shift_id=ANY(shifts) ORDER BY shift_id FOR UPDATE;
    IF EXISTS(SELECT 1 FROM pantry_shift WHERE shift_id=ANY(shifts) AND status<>'PLANNED') THEN
        RAISE EXCEPTION 'Staff assignments can only change while a shift is PLANNED';
    END IF;
    IF TG_OP='DELETE' THEN RETURN OLD; END IF;
    IF NOT EXISTS(SELECT 1 FROM staff WHERE unikey=NEW.staff_unikey AND is_active) THEN
        RAISE EXCEPTION 'Only active staff can be assigned to a shift';
    END IF;
    SELECT * INTO sh FROM pantry_shift WHERE shift_id=NEW.shift_id;
    IF EXISTS (
        SELECT 1 FROM shift_staff_assignment a JOIN pantry_shift p USING(shift_id)
        WHERE a.staff_unikey=NEW.staff_unikey
          -- BEFORE INSERT also runs for UPSERT: its existing target is not an overlap.
          AND (a.shift_id,a.staff_unikey) IS DISTINCT FROM (NEW.shift_id,NEW.staff_unikey)
          AND (TG_OP='INSERT' OR (a.shift_id,a.staff_unikey) IS DISTINCT FROM (OLD.shift_id,OLD.staff_unikey))
          AND p.shift_date=sh.shift_date AND p.start_time<sh.end_time AND sh.start_time<p.end_time
    ) THEN
        RAISE EXCEPTION 'Staff member % is already assigned to an overlapping shift', NEW.staff_unikey;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER staff_shift_assignment_validate
BEFORE INSERT OR UPDATE OR DELETE ON shift_staff_assignment
FOR EACH ROW EXECUTE FUNCTION validate_staff_shift_assignment();

CREATE FUNCTION validate_volunteer_shift() RETURNS trigger
LANGUAGE plpgsql SET search_path = campus_pantry, public AS $$
DECLARE
    people varchar[];
    shifts integer[];
    sh record;
BEGIN
    IF TG_OP='DELETE' THEN
        people:=ARRAY[OLD.volunteer_unikey]; shifts:=ARRAY[OLD.shift_id];
    ELSE
        people:=ARRAY[NEW.volunteer_unikey]; shifts:=ARRAY[NEW.shift_id];
        IF TG_OP='UPDATE' THEN
            people:=array_append(people,OLD.volunteer_unikey);
            shifts:=array_append(shifts,OLD.shift_id);
        END IF;
    END IF;
    PERFORM unikey FROM volunteer WHERE unikey=ANY(people) ORDER BY unikey FOR UPDATE;
    PERFORM shift_id FROM pantry_shift WHERE shift_id=ANY(shifts) ORDER BY shift_id FOR SHARE;
    IF EXISTS(SELECT 1 FROM pantry_shift WHERE shift_id=ANY(shifts) AND status='CLOSED') THEN
        RAISE EXCEPTION 'Volunteer requests cannot change on a CLOSED shift';
    END IF;
    IF TG_OP='DELETE' THEN RETURN OLD; END IF;
    IF NEW.status IN ('PENDING','APPROVED') THEN
        IF NOT EXISTS(SELECT 1 FROM volunteer WHERE unikey=NEW.volunteer_unikey AND is_active) THEN
            RAISE EXCEPTION 'Only active volunteers can request or join shifts';
        END IF;
        SELECT * INTO sh FROM pantry_shift WHERE shift_id=NEW.shift_id;
        IF EXISTS (
            SELECT 1 FROM volunteer_shift v JOIN pantry_shift p USING(shift_id)
            WHERE v.volunteer_unikey=NEW.volunteer_unikey AND v.status IN ('PENDING','APPROVED')
              AND (TG_OP='INSERT' OR (v.shift_id,v.volunteer_unikey) IS DISTINCT FROM (OLD.shift_id,OLD.volunteer_unikey))
              AND p.shift_date=sh.shift_date AND p.start_time<sh.end_time AND sh.start_time<p.end_time
        ) THEN
            RAISE EXCEPTION 'Volunteer % has an overlapping shift request or assignment', NEW.volunteer_unikey;
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER volunteer_shift_validate
BEFORE INSERT OR UPDATE OR DELETE ON volunteer_shift
FOR EACH ROW EXECUTE FUNCTION validate_volunteer_shift();

-- Schedules are immutable after creation. Create another shift/session to correct
-- a schedule rather than changing the date or time of existing reservations.
CREATE FUNCTION validate_session() RETURNS trigger
LANGUAGE plpgsql SET search_path = campus_pantry, public AS $$
DECLARE sh record; used integer;
BEGIN
    IF TG_OP='UPDATE' AND (NEW.shift_id,NEW.session_date,NEW.start_time,NEW.end_time)
        IS DISTINCT FROM (OLD.shift_id,OLD.session_date,OLD.start_time,OLD.end_time) THEN
        RAISE EXCEPTION 'Session schedule is immutable; create a new session';
    END IF;
    IF TG_OP='INSERT' THEN
        SELECT * INTO sh FROM pantry_shift WHERE shift_id=NEW.shift_id FOR UPDATE;
        IF NEW.session_date<>sh.shift_date OR NEW.start_time<sh.start_time OR NEW.end_time>sh.end_time THEN
            RAISE EXCEPTION 'Session must fall within the assigned shift date and time';
        END IF;
        IF sh.status<>'PLANNED' THEN
            RAISE EXCEPTION 'Sessions can only be added to a PLANNED shift';
        END IF;
        IF EXISTS (SELECT 1 FROM session x WHERE x.shift_id=NEW.shift_id
            AND x.start_time<NEW.end_time AND NEW.start_time<x.end_time) THEN
            RAISE EXCEPTION 'Session times cannot overlap within a shift';
        END IF;
    END IF;
    IF TG_OP='UPDATE' AND NEW.capacity IS DISTINCT FROM OLD.capacity THEN
        SELECT count(*) INTO used FROM booking WHERE session_id=NEW.session_id AND status<>'CANCELLED';
        IF NEW.capacity<used THEN
            RAISE EXCEPTION 'Capacity cannot be reduced below % non-cancelled bookings',used;
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER session_validate BEFORE INSERT OR UPDATE ON session
FOR EACH ROW EXECUTE FUNCTION validate_session();

CREATE FUNCTION validate_shift() RETURNS trigger
LANGUAGE plpgsql SET search_path = campus_pantry, public AS $$
DECLARE super_cnt integer; asst_cnt integer;
BEGIN
    IF TG_OP='INSERT' AND NEW.status<>'PLANNED' THEN
        RAISE EXCEPTION 'New shifts must start as PLANNED';
    END IF;
    IF TG_OP='UPDATE' THEN
        IF (NEW.shift_date,NEW.start_time,NEW.end_time) IS DISTINCT FROM
           (OLD.shift_date,OLD.start_time,OLD.end_time) THEN
            RAISE EXCEPTION 'Shift date and times are immutable; create a new shift';
        END IF;
        IF NEW.status IS DISTINCT FROM OLD.status AND NOT
          ((OLD.status='PLANNED' AND NEW.status='OPEN') OR (OLD.status='OPEN' AND NEW.status='CLOSED')) THEN
            RAISE EXCEPTION 'Shift transitions must follow PLANNED to OPEN to CLOSED';
        END IF;
    END IF;
    IF NEW.status IN ('OPEN','CLOSED') THEN
        SELECT count(*) FILTER(WHERE assignment_role='MAIN_SUPERVISOR'),
               count(*) FILTER(WHERE assignment_role='ASSISTANT')
        INTO super_cnt,asst_cnt FROM shift_staff_assignment WHERE shift_id=NEW.shift_id;
        IF super_cnt<>1 OR asst_cnt<>1 THEN
            RAISE EXCEPTION 'Shift % must have exactly 1 MAIN_SUPERVISOR and 1 ASSISTANT before it can be %',NEW.shift_id,NEW.status;
        END IF;
    END IF;
    IF NEW.status='OPEN' AND EXISTS (
        SELECT 1 FROM shift_staff_assignment a JOIN staff st ON st.unikey=a.staff_unikey
        WHERE a.shift_id=NEW.shift_id AND NOT st.is_active
    ) THEN
        RAISE EXCEPTION 'A shift can only open with active assigned staff';
    END IF;
    IF NEW.status='CLOSED' THEN
        IF EXISTS(SELECT 1 FROM shift_stock_count WHERE shift_id=NEW.shift_id AND closing_qty IS NULL) THEN
            RAISE EXCEPTION 'Every opening stock count needs a closing count before closing the shift';
        END IF;
        IF EXISTS(
            SELECT 1 FROM shift_stock_count s
            LEFT JOIN stock_adjustment r ON (r.shift_id,r.stock_number,r.adjustment_kind)=(s.shift_id,s.stock_number,'RECEIPT')
            LEFT JOIN stock_adjustment w ON (w.shift_id,w.stock_number,w.adjustment_kind)=(s.shift_id,s.stock_number,'WASTE')
            WHERE s.shift_id=NEW.shift_id AND s.opening_qty+coalesce(r.quantity,0)-coalesce(w.quantity,0)-s.closing_qty<0
        ) THEN
            RAISE EXCEPTION 'Stock reconciliation cannot have negative estimated dispensing';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER shift_validate BEFORE INSERT OR UPDATE ON pantry_shift
FOR EACH ROW EXECUTE FUNCTION validate_shift();

-- Lock the parent shift so closing and inventory writes cannot pass each other.
CREATE FUNCTION guard_closed_shift_inventory() RETURNS trigger
LANGUAGE plpgsql SET search_path = campus_pantry, public AS $$
DECLARE ids integer[]; sh_status varchar;
BEGIN
    IF TG_OP='DELETE' THEN ids:=ARRAY[OLD.shift_id];
    ELSE
        ids:=ARRAY[NEW.shift_id];
        IF TG_OP='UPDATE' THEN ids:=array_append(ids,OLD.shift_id); END IF;
    END IF;
    PERFORM shift_id FROM pantry_shift WHERE shift_id=ANY(ids) ORDER BY shift_id FOR UPDATE;
    IF EXISTS(SELECT 1 FROM pantry_shift WHERE shift_id=ANY(ids) AND status='CLOSED') THEN
        RAISE EXCEPTION 'Inventory records cannot change on a CLOSED shift';
    END IF;
    IF TG_OP='DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER stock_count_shift_guard BEFORE INSERT OR UPDATE OR DELETE ON stock_count
FOR EACH ROW EXECUTE FUNCTION guard_closed_shift_inventory();
CREATE TRIGGER shift_stock_count_shift_guard BEFORE INSERT OR UPDATE OR DELETE ON shift_stock_count
FOR EACH ROW EXECUTE FUNCTION guard_closed_shift_inventory();
CREATE TRIGGER stock_adjustment_shift_guard BEFORE INSERT OR UPDATE OR DELETE ON stock_adjustment
FOR EACH ROW EXECUTE FUNCTION guard_closed_shift_inventory();


-- Views
CREATE OR REPLACE VIEW v_booking_attendance AS
SELECT s.session_date, s.session_id, s.start_time, s.end_time, s.capacity,
       count(b.booking_id) FILTER (WHERE b.status <> 'CANCELLED') AS active_bookings,
       count(b.booking_id) FILTER (WHERE b.status = 'ATTENDED') AS attended,
       count(b.booking_id) FILTER (WHERE b.status = 'ABSENT') AS absent,
       count(b.booking_id) FILTER (WHERE b.status = 'CONFIRMED') AS awaiting_checkin,
       s.capacity - count(b.booking_id) FILTER (WHERE b.status <> 'CANCELLED') AS spaces_remaining
FROM session s LEFT JOIN booking b ON b.session_id = s.session_id
GROUP BY s.session_id;

CREATE OR REPLACE VIEW v_latest_stock_count AS
SELECT DISTINCT ON (sc.stock_number)
       sc.stock_number, sb.product_id, p.product_name, p.counting_unit,
       sc.counted_qty AS last_counted_qty, sc.counted_at, sc.count_type,
       sc.counted_by_staff
FROM stock_count sc
JOIN stock_batch sb ON sb.stock_number = sc.stock_number
JOIN product p ON p.product_id = sb.product_id
ORDER BY sc.stock_number, sc.counted_at DESC, sc.stock_count_id DESC;

CREATE OR REPLACE VIEW v_shift_stock_report AS
SELECT sh.shift_id, sh.shift_date, sh.start_time, sh.end_time,
       ssc.stock_number, p.product_id, p.product_name, p.counting_unit,

       ssc.opening_qty, coalesce(r.quantity,0) AS received_qty,
       coalesce(w.quantity,0) AS waste_qty, ssc.closing_qty,
       CASE WHEN sh.status = 'CLOSED' AND ssc.closing_qty IS NOT NULL
            THEN ssc.opening_qty + coalesce(r.quantity,0)
                 - coalesce(w.quantity,0) - ssc.closing_qty END AS estimated_dispensed_qty,
       ssc.opening_variance_reason
FROM shift_stock_count ssc
JOIN pantry_shift sh ON sh.shift_id = ssc.shift_id
JOIN stock_batch sb ON sb.stock_number = ssc.stock_number
JOIN product p ON p.product_id = sb.product_id
LEFT JOIN stock_adjustment r ON r.shift_id = ssc.shift_id
    AND r.stock_number = ssc.stock_number AND r.adjustment_kind = 'RECEIPT'
LEFT JOIN stock_adjustment w ON w.shift_id = ssc.shift_id
    AND w.stock_number = ssc.stock_number AND w.adjustment_kind = 'WASTE';

COMMIT;
