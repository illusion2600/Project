"""Own a disposable PostgreSQL DB. Reads TEST_PG* only, never app .env/PGDATABASE."""
from contextlib import contextmanager
from pathlib import Path
import os
import re
import secrets
import psycopg2
from psycopg2 import sql

ROOT = Path(__file__).resolve().parents[1]
_current = None


class Sandbox:
    def __init__(self, settings, database):
        if not re.fullmatch(r"campus_pantry_test_[0-9a-f]{24}", database):
            raise ValueError("Refusing a database name not generated by the sandbox.")
        self.settings = dict(settings, dbname=database)
        self.database = database
        self.created = False
        self.removed = False
        self.server_version = None
        self.connections = []

    def connect(self):
        if not self.created or self.removed:
            raise RuntimeError("The owned disposable database is not active.")
        conn = psycopg2.connect(**self.settings)
        self.connections.append(conn)
        with conn:
            with conn.cursor() as cur:
                cur.execute("SELECT current_database()")
                if cur.fetchone()[0] != self.database:
                    conn.close()
                    raise RuntimeError("Disposable database identity mismatch.")
                cur.execute("SET search_path = campus_pantry, public")
                cur.execute("SET timezone = 'Australia/Sydney'")
                cur.execute("SET statement_timeout = '12s'")
                cur.execute("SET lock_timeout = '8s'")
        return conn

    def reset(self, conn):
        """Reload canonical SQL only inside this owned disposable database."""
        conn.rollback()
        with conn.cursor() as cur:
            cur.execute("SELECT current_database()")
            if cur.fetchone()[0] != self.database or not self.created or self.removed:
                raise RuntimeError("Refusing to reset an unowned database.")
            cur.execute("DROP SCHEMA IF EXISTS campus_pantry CASCADE")
        conn.commit()
        for name in ("01_schema.sql", "02_seed_data.sql"):
            source = (ROOT / "campus_pantry_sql" / name).read_text(encoding="utf-8-sig")
            if re.search(r"^\s*\\", source, re.M):
                raise RuntimeError(f"Canonical {name} must be plain SQL.")
            with conn.cursor() as cur:
                cur.execute(source)
            conn.commit()


def admin_settings():
    user = os.environ.get("TEST_PGUSER")
    if not user:
        raise ValueError("Set TEST_PGUSER explicitly to a PostgreSQL role with CREATEDB permission.")
    try:
        port = int(os.environ.get("TEST_PGPORT", "5432"))
        if not 1 <= port <= 65535:
            raise ValueError
    except ValueError as exc:
        raise ValueError("TEST_PGPORT must be an integer from 1 to 65535.") from exc
    config = {
        "host": os.environ.get("TEST_PGHOST", "127.0.0.1"),
        "port": port,
        "user": user,
        "dbname": os.environ.get("TEST_PGMAINTENANCE_DB", "postgres"),
        "connect_timeout": 5,
        "application_name": "campus_pantry_disposable_sandbox",
        "sslmode": os.environ.get("TEST_PGSSLMODE", "prefer"),
    }
    if "TEST_PGPASSWORD" in os.environ:
        config["password"] = os.environ["TEST_PGPASSWORD"]
    return config


@contextmanager
def disposable_database(label="TEST"):
    """Yield Sandbox; close connections and drop exactly its owned database.

    label is descriptive. Generated database name and ownership marker are
    independently checked. No caller-selected target database is accepted.
    """
    config = admin_settings()
    sandbox = Sandbox(config, "campus_pantry_test_" + secrets.token_hex(12))
    marker = "Campus Pantry owned sandbox " + str(label) + " " + secrets.token_hex(24)
    admin = psycopg2.connect(**config)
    admin.autocommit = True
    sandbox.server_version = admin.server_version
    try:
        with admin.cursor() as cur:
            cur.execute(sql.SQL("CREATE DATABASE {} TEMPLATE template0 ENCODING 'UTF8'").format(
                sql.Identifier(sandbox.database)))
            sandbox.created = True
            cur.execute(sql.SQL("COMMENT ON DATABASE {} IS %s").format(
                sql.Identifier(sandbox.database)), (marker,))
        yield sandbox
    finally:
        for conn in sandbox.connections:
            if not conn.closed:
                conn.close()
        try:
            if sandbox.created:
                with admin.cursor() as cur:
                    cur.execute("SELECT shobj_description(oid, 'pg_database') FROM pg_database WHERE datname=%s",
                                (sandbox.database,))
                    row = cur.fetchone()
                    if row is None or row[0] != marker:
                        raise RuntimeError("Ownership check failed; refusing to drop database.")
                    cur.execute("SELECT pg_terminate_backend(pid) FROM pg_stat_activity "
                                "WHERE datname=%s AND pid<>pg_backend_pid()", (sandbox.database,))
                    cur.execute(sql.SQL("DROP DATABASE {}").format(sql.Identifier(sandbox.database)))
                    sandbox.removed = True
        finally:
            admin.close()


def configure(sandbox):
    global _current
    _current = sandbox


def connect():
    if _current is None:
        raise RuntimeError("Run tests through tests/run_tests.py; no owned test database is configured.")
    return _current.connect()


def reset(conn):
    if _current is None:
        raise RuntimeError("No owned test database is configured.")
    _current.reset(conn)
